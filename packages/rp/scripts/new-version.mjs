import { readManifest, writeManifest } from './load-prototype.mjs';
import { execFileSync } from 'node:child_process';
const [id, title, baselineId] = process.argv.slice(2).filter(arg => arg !== '--');
const catalog = readManifest();
if (catalog.releases.some(item => item.status === 'in_progress')) throw new Error('请先提交实现并完结当前进行中版本');
if (!/^v\d+\.\d+(?:\.\d+)?$/.test(id ?? '') || !title?.trim() || catalog.releases.some(item => item.id === id)) throw new Error('用法：pnpm version:new -- v0.9 "版本标题" <已完结基线>');
const baseline = catalog.releases.find(item => item.id === baselineId && item.status === 'completed' && !item.supersededBy);
if (!baseline) throw new Error('必须明确选择已完结版本作为基线');
const editBase = execFileSync('git', ['rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
const prefix = execFileSync('git', ['rev-parse', '--show-prefix'], { encoding: 'utf8' }).trim().replace(/\/$/, '');
const editBaseTree = execFileSync('git', ['rev-parse', prefix ? `HEAD:${prefix}` : 'HEAD^{tree}'], { encoding: 'utf8' }).trim();
catalog.releases.unshift({ id, routeSchema: 2, title, status: 'in_progress', baseline: baseline.id, date: new Date().toISOString().slice(0, 10), sourceCommit: null, editBase, editBaseTree, goal: title, changes: [] });
catalog.current = id; catalog.activeVersion = id;
writeManifest(catalog);
console.log(`已登记 ${id}，请通过 AI 补全目标、页面和 CHG 后提交。`);
