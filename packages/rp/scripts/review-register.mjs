import { readManifest } from './load-prototype.mjs';
import { readFile, writeFile } from 'node:fs/promises';
import { repository } from '../prototype/project.mjs';
import { github } from './github-api.mjs';
import { readDiscussion } from './discussion-api.mjs';
import { parseHandoff, normalizeHandoff } from '../prototype/handoff.mjs';
const [version, target] = process.argv.slice(2).filter((value) => value !== '--');
const discussion = target?.startsWith('discussion:');
const input = discussion ? target.slice(11) : target;
const file = discussion ? 'prototype/discussions.json' : 'prototype/reviews.json';
const catalog = readManifest(process.cwd(), { allowLegacy: true });
if (!catalog.releases.some((item) => item.id === version) || !/^[1-9]\d*$/.test(input || '')) throw new Error('用法：pnpm version:review -- v0.6 <discussion:编号>（旧版 Issue 可用数字编号）');
const release = catalog.releases.find((item) => item.id === version);
if (discussion && (release.supersededBy || ['finalized', 'baseline'].includes(release.status))) throw new Error('历史版本不能更换评审来源，请在新版本创建 Discussion');
const issue = discussion ? await readDiscussion(Number(input)) : await github(`repos/${repository}/issues/${input}`);
if (issue.pull_request || issue.state !== 'open' || normalizeHandoff(parseHandoff(issue.body), release).version !== version) throw new Error('需要匹配版本、包含结构化交接记录的 open 评审记录');
const registry = JSON.parse(await readFile(file, 'utf8'));
if (registry[version] && registry[version] !== Number(input)) throw new Error('已有不同评审记录，需人工核对迁移，拒绝覆盖');
if (Object.entries(registry).some(([key, number]) => key !== version && number === Number(input))) throw new Error('一个评审记录不能承接两个版本');
registry[version] = Number(input);
await writeFile(file, JSON.stringify(registry, null, 2) + '\n');
console.log(`已登记 ${version} → ${discussion ? 'Discussion' : 'Issue'} #${input}；请将登记与版本说明一起提交。`);
